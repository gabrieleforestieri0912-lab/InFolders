let currentLang: LanguageCode = 'it';
let strings: Record<string, string> = {};

function loadStrings(lang: LanguageCode): void {
  const langData = LANGUAGES[lang] || LANGUAGES.it;
  strings = langData.strings;
  currentLang = lang;
}

export function initLanguage(callback?: (lang: LanguageCode) => void): void {
  const detected = (navigator.language || 'it').split('-')[0] as LanguageCode;
  chrome.storage.local.get(['infolders_lang'], (result) => {
    const lang: LanguageCode = (result.infolders_lang as LanguageCode) || (LANGUAGES[detected] ? detected : 'it');
    loadStrings(lang);
    if (callback) callback(lang);
  });
}

export function setLanguage(lang: LanguageCode, callback?: (lang: LanguageCode) => void): void {
  if (!LANGUAGES[lang]) return;
  loadStrings(lang);
  chrome.storage.local.set({ infolders_lang: lang }, () => {
    if (callback) callback(lang);
  });
}

export function getCurrentLang(): LanguageCode {
  return currentLang;
}

export function getAvailableLanguages(): { code: LanguageCode; name: string }[] {
  return Object.entries(LANGUAGES).map(([code, data]) => ({
    code: code as LanguageCode,
    name: data.nativeName
  }));
}

export function t(key: string, params: Record<string, string | number> = {}): string {
  let str = strings[key] || LANGUAGES.it.strings[key] || key;
  for (const [k, v] of Object.entries(params)) {
    str = str.replace(`{${k}}`, String(v));
  }
  return str;
}

